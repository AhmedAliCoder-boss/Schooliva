import Image from "next/image";
import type { ReactNode } from "react";

type SchoolIdentity = {
  name: string;
  code: string;
  email: string | null;
  phone: string | null;
  address: string | null;
  city: string | null;
  state: string | null;
  country: string | null;
  postal_code: string | null;
  logoUrl: string | null;
};

export function SchoolDocument({
  school,
  title,
  reference,
  children,
  className,
}: {
  school: SchoolIdentity;
  title: string;
  reference?: string;
  children: ReactNode;
  className?: string;
}) {
  const address = [school.address, school.city, school.state, school.postal_code, school.country].filter(Boolean).join(", ");
  return <article className={["school-document", className].filter(Boolean).join(" ")}>
    <header className="school-document__header">
      {school.logoUrl && <Image className="school-document__logo" src={school.logoUrl} alt={`${school.name} logo`} width={104} height={76} unoptimized />}
      <div className="school-document__identity">
        <h1>{school.name}</h1>
        <p>{address || `School code: ${school.code}`}</p>
        {(school.phone || school.email) && <p>{[school.phone, school.email].filter(Boolean).join(" · ")}</p>}
      </div>
      <div className="school-document__title"><h2>{title}</h2>{reference && <p>Ref: {reference}</p>}</div>
    </header>
    <div className="school-document__body">{children}</div>
    <footer className="school-document__footer">
      <span>Generated by Schooliva</span>
      <span>{new Intl.DateTimeFormat("en", { dateStyle: "medium" }).format(new Date())}</span>
    </footer>
  </article>;
}
